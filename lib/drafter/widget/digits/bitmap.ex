  @pixels Map.new(@shapes, fn {character, rows} ->
            lit =
              for {row, y} <- Enum.with_index(rows),
                  {pixel, x} <- Enum.with_index(String.graphemes(row)),
                  pixel == "#",
                  into: MapSet.new(),
                  do: {x, y + @ascender_rows}

            {character, lit}
          end)

  @doc "Pixel width of every bitmap, side bearing included."
  @spec width() :: pos_integer()
  def width, do: @width

  @doc "Pixel height of every bitmap, ascender space and leading included."
  @spec height() :: pos_integer()
  def height, do: @height

  @doc "Every character with a bitmap, sorted."
  @spec characters() :: [String.t()]
  def characters, do: @pixels |> Map.keys() |> Enum.sort()

  @doc """
  The lit pixels of a character as a `MapSet` of `{x, y}`, origin top left.

  Returns an empty set for a character with no bitmap.
  """
  @spec pixels(String.t()) :: MapSet.t({non_neg_integer(), non_neg_integer()})
  def pixels(character) do
    Map.get(@pixels, character) || Map.get(@pixels, String.upcase(character)) || MapSet.new()
  end

  @doc "Whether a character has a bitmap in some case."
  @spec drawable?(String.t()) :: boolean()
  def drawable?(character) do
    Map.has_key?(@pixels, character) or Map.has_key?(@pixels, String.upcase(character))
  end
end
